"""Pydantic V2 Schemas and Data Contracts for AegisRansom-X.

Conforms strictly to ARCHITECTURE.md Section 3 Data Contracts.
"""

from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field


class EventType(str, Enum):
    FILE_CREATE = "FILE_CREATE"
    FILE_MODIFY = "FILE_MODIFY"
    FILE_RENAME = "FILE_RENAME"
    FILE_DELETE = "FILE_DELETE"


class IncidentStatus(str, Enum):
    ACTIVE = "ACTIVE"
    CONTAINED = "CONTAINED"
    RELEASED = "RELEASED"
    TERMINATED = "TERMINATED"
    RESTORED = "RESTORED"


class AnalystAction(str, Enum):
    RESUME_SIGCONT = "RESUME_SIGCONT"
    TERMINATE_SIGKILL = "TERMINATE_SIGKILL"
    ROLLBACK_RESTORE = "ROLLBACK_RESTORE"


class TelemetryEvent(BaseModel):
    """Telemetry Event Payload generated by macOS filesystem listener (agent/watcher.py)."""
    event_id: str = Field(description="Unique event ID (e.g., evt_4b2c1d)")
    timestamp: float = Field(description="POSIX epoch timestamp")
    event_type: EventType = Field(description="Filesystem event type")
    file_path: str = Field(description="Target file path")
    entropy_before: float = Field(default=0.0, description="Pre-modification Shannon entropy [0.0 - 8.0]")
    entropy_after: float = Field(default=0.0, description="Post-modification Shannon entropy [0.0 - 8.0]")
    entropy_delta: float = Field(default=0.0, description="Change in entropy (after - before)")
    pid: Optional[int] = Field(default=None, description="Attributed process PID")
    process_name: Optional[str] = Field(default=None, description="Attributed process name")
    is_canary: bool = Field(default=False, description="True if event targets a micro-canary honeyfile")


class XAIFactor(BaseModel):
    """Deterministic Explainable AI signal factor and weight."""
    factor: str = Field(description="Factor identifier (e.g. CANARY_TRIPWIRE, ENTROPY_JUMP_ABOVE_7_5)")
    weight: float = Field(description="Normalized attribution weight (0.0 to 1.0)")


class IncidentAlert(BaseModel):
    """Security Incident & XAI Payload broadcast via WebSocket /ws/alerts."""
    incident_id: str = Field(description="Unique incident ID (e.g., inc_99a8b7)")
    timestamp: float = Field(description="POSIX epoch timestamp")
    status: IncidentStatus = Field(default=IncidentStatus.CONTAINED, description="Incident status")
    risk_score: float = Field(ge=0.0, le=100.0, description="Composite risk score [0.0 - 100.0]")
    offending_pid: int = Field(description="Suspended or culprit PID")
    process_name: str = Field(description="Process name of the culprit")
    files_affected_count: int = Field(ge=0, description="Number of files affected before containment")
    detection_latency_ms: float = Field(description="Detection latency in milliseconds")
    containment_method: str = Field(default="POSIX_SIGSTOP", description="Containment action executed")
    xai_breakdown: List[XAIFactor] = Field(default_factory=list, description="Top contributing signals")


class ActionRequest(BaseModel):
    """Analyst action request payload (POST /api/v1/actions)."""
    incident_id: str = Field(description="Target incident ID")
    action: AnalystAction = Field(description="Action to execute")


class IncidentActionRequest(BaseModel):
    """Analyst action request payload (POST /api/incidents/{incident_id}/action)."""
    action: AnalystAction = Field(description="Action to execute: RESUME_SIGCONT, TERMINATE_SIGKILL, or ROLLBACK_RESTORE")


class SimulatorStartRequest(BaseModel):
    """Request payload to launch the safe simulator (POST /api/simulator/start)."""
    mode: str = Field(default="normal", description="Speed profile: burst, normal, or stealth")
    extension: str = Field(default=".locked", description="Target mutated extension (default: .locked)")
    delay: Optional[float] = Field(default=None, description="Custom delay in seconds between files")
    max_files: Optional[int] = Field(default=None, description="Max files to encrypt")


class CopilotNarrativeResponse(BaseModel):
    """Response payload for Tier-2 AI Copilot incident briefings."""
    type: str = Field(default="copilot", description="Message type")
    incident_id: str = Field(description="Associated incident identifier")
    status: str = Field(description="Analysis status: analyzing, streaming, completed, failed")
    model: str = Field(description="Model used: gemma:2b or deterministic_xai")
    done: bool = Field(default=True, description="Whether generation is complete")
    narrative: str = Field(description="Full or accumulated narrative text")
    fallback: bool = Field(default=False, description="True if offline deterministic fallback was used")
    timestamp: Optional[float] = Field(default=None, description="Timestamp of generation")


